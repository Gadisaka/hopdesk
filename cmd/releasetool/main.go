// Command releasetool creates the update signing key and signs releases.
//
//	go run ./cmd/releasetool keygen
//	    Makes a new key pair. Writes the private key to hopdesk-update.key
//	    (keep it secret: it goes into the HOPDESK_UPDATE_KEY GitHub secret) and
//	    the public key into cmd/agent/update_key.go (commit that file).
//
//	HOPDESK_UPDATE_KEY=... go run ./cmd/releasetool sign -version v1.2.3 -dir dist
//	    Writes dist/latest.json and dist/latest.json.sig for the installers in dist.
package main

import (
	"crypto/ed25519"
	"crypto/rand"
	"encoding/base64"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"hopdesk/internal/update"
)

const repo = "gadisaka/hopdesk"

func main() {
	if len(os.Args) < 2 {
		usage()
	}
	var err error
	switch os.Args[1] {
	case "keygen":
		err = keygen(os.Args[2:])
	case "sign":
		err = sign(os.Args[2:])
	default:
		usage()
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "releasetool:", err)
		os.Exit(1)
	}
}

func usage() {
	fmt.Fprintln(os.Stderr, "usage: releasetool keygen [-force]\n       releasetool sign -version vX.Y.Z [-dir dist]")
	os.Exit(2)
}

func keygen(args []string) error {
	fs := flag.NewFlagSet("keygen", flag.ExitOnError)
	keyFile := fs.String("key", "hopdesk-update.key", "where to write the private key")
	goFile := fs.String("go", filepath.Join("cmd", "agent", "update_key.go"), "where to write the public key")
	force := fs.Bool("force", false, "replace an existing key (installed copies will stop accepting updates)")
	_ = fs.Parse(args)

	if _, err := os.Stat(*keyFile); err == nil && !*force {
		return fmt.Errorf("%s already exists; use -force to replace it", *keyFile)
	}
	pub, priv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		return err
	}
	seed := base64.StdEncoding.EncodeToString(priv.Seed())
	if err := os.WriteFile(*keyFile, []byte(seed+"\n"), 0o600); err != nil {
		return err
	}
	src := fmt.Sprintf(`package main

// updatePublicKey verifies signed release manifests (see internal/update).
// Generated by: go run ./cmd/releasetool keygen
const updatePublicKey = %q
`, base64.StdEncoding.EncodeToString(pub))
	if err := os.WriteFile(*goFile, []byte(src), 0o644); err != nil {
		return err
	}
	fmt.Printf(`Created the update signing key.

  Private key: %s   <- secret. Add it to GitHub, then keep a backup somewhere safe:
                 gh secret set HOPDESK_UPDATE_KEY < %s
               (or GitHub → Settings → Secrets and variables → Actions → New secret,
                name HOPDESK_UPDATE_KEY, value: the line in that file)
  Public key:  %s   <- commit this file.

Never commit the private key. Anyone who has it can publish updates for HopDesk.
`, *keyFile, *keyFile, *goFile)
	return nil
}

func loadKey() (ed25519.PrivateKey, error) {
	s := strings.TrimSpace(os.Getenv("HOPDESK_UPDATE_KEY"))
	if s == "" {
		return nil, errors.New("HOPDESK_UPDATE_KEY is not set")
	}
	seed, err := base64.StdEncoding.DecodeString(s)
	if err != nil || len(seed) != ed25519.SeedSize {
		return nil, errors.New("HOPDESK_UPDATE_KEY is not a valid key (expected the line from hopdesk-update.key)")
	}
	return ed25519.NewKeyFromSeed(seed), nil
}

func sign(args []string) error {
	fs := flag.NewFlagSet("sign", flag.ExitOnError)
	ver := fs.String("version", "", "release version, e.g. v1.2.3")
	dir := fs.String("dir", "dist", "folder with the installers")
	_ = fs.Parse(args)

	if v, ok := update.ParseVersion(*ver); !ok || v.Ahead != 0 {
		return fmt.Errorf("-version must be a release version like v1.2.3, got %q", *ver)
	}
	priv, err := loadKey()
	if err != nil {
		return err
	}
	m := update.Manifest{
		Version:   *ver,
		Published: time.Now().UTC().Format(time.RFC3339),
		NotesURL:  fmt.Sprintf("https://github.com/%s/releases/tag/%s", repo, *ver),
		Assets:    map[string]update.Asset{},
	}
	for platform, pattern := range map[string]string{
		update.PlatformMac:     "HopDesk-*-macOS.dmg",
		update.PlatformWindows: "HopDesk-*-Windows-Setup.exe",
	} {
		matches, _ := filepath.Glob(filepath.Join(*dir, pattern))
		if len(matches) != 1 {
			fmt.Fprintf(os.Stderr, "releasetool: skipping %s: expected one %s in %s, found %d\n", platform, pattern, *dir, len(matches))
			continue
		}
		f, err := os.Open(matches[0])
		if err != nil {
			return err
		}
		sum, size, err := update.SHA256Reader(f)
		f.Close()
		if err != nil {
			return err
		}
		m.Assets[platform] = update.Asset{Name: filepath.Base(matches[0]), SHA256: sum, Size: size}
	}
	if len(m.Assets) == 0 {
		return errors.New("no installers found")
	}
	if err := m.Validate(); err != nil {
		return err
	}
	data, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return err
	}
	data = append(data, '\n')
	if err := os.WriteFile(filepath.Join(*dir, "latest.json"), data, 0o644); err != nil {
		return err
	}
	sig := update.Sign(priv, data)
	if err := os.WriteFile(filepath.Join(*dir, "latest.json.sig"), []byte(sig+"\n"), 0o644); err != nil {
		return err
	}
	fmt.Printf("Signed %s: %s\n", *ver, strings.Join(names(m), ", "))
	return nil
}

func names(m update.Manifest) []string {
	var out []string
	for _, a := range m.Assets {
		out = append(out, a.Name)
	}
	return out
}
